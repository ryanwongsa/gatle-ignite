def where_things_go_page():
    """The scaffold README's layout table, so the site and `init` cannot drift apart."""
    source = files("gatle_ignite").joinpath("_template", "README.md-tpl")
    template = source.read_text(encoding="utf-8").replace("{{project_name}}", "my_project")
    start = template.index("## Where things go")
    end = template.index("Copy-paste templates", start)

    out = io.StringIO()
    print("# Where things go\n", file=out)
    print(BANNER, file=out)
    print(
        "\nThe table `gatle-ignite init` writes into your project's README, generated from that"
        " same file so the two cannot drift.\n",
        file=out,
    )
    print(template[start:end].split("\n", 1)[1].strip(), file=out)
    print("\nCopy-paste skeletons for each: [Templates](../templates.md).", file=out)
    return out.getvalue()


PAGES = (
    (
        "reference/where-things-go.md",
        where_things_go_page,
        "src/gatle_ignite/_template/README.md-tpl",
    ),
    ("reference/config.md", config_page, "src/gatle_ignite/config/base.py"),
    ("reference/contracts.md", contracts_page, "src/gatle_ignite/dispatch.py"),
    ("reference/builtins.md", builtins_page, "docs/gen_reference.py"),
    ("getting-started/cli.md", cli_page, "src/gatle_ignite/cli/main.py"),
)

for path, render, edit_hint in PAGES:
    with mkdocs_gen_files.open(path, "w") as f:
        f.write(render())
    # Point Material's edit pencil at the source, not at a file that doesn't exist,
    # so the next reader learns where the truth lives.
    mkdocs_gen_files.set_edit_path(path, edit_hint)
