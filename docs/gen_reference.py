def _trailing_comments(src):
    """{line number: text} for every comment that FOLLOWS code on its own line.

    Found by token rather than by slicing a line, because a field's note is not reliably on
    the statement's LAST line. `ruff format` wraps a too-long `cfg.x = 1  # note` by
    parenthesising the value:

        cfg.max_epochs = (
            1  # note
        )

    which leaves `end_lineno` pointing at the `)` and the note a line above it. Slicing
    that last line then finds no `#`, and the field silently loses its Notes cell: a doc
    that goes blank with a green build, which is the exact failure this generator exists to
    prevent. Keyed by line so the caller can take whatever falls inside a statement's span,
    wherever the formatter put it.
    """
    comments = {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type != tokenize.COMMENT:
            continue
        if tok.line[: tok.start[1]].strip():  # code precedes it: trailing, not whole-line
            comments[tok.start[0]] = tok.string.lstrip("#").strip()
    return comments


def _walk_base_config():
    """Yield (section, name, default_src, note) for every `cfg.X = ...` in base_config().

    Read by AST rather than by introspecting the returned ConfigDict, because only the
    source carries the `# --- section ---` groupings and the per-field comments.
    """
    source = inspect.getsource(base)
    lines = inspect.getsourcelines(base)[0]
    tree = ast.parse(source)
    trailing = _trailing_comments(source)
    fn = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "base_config")

    section = None
    for stmt in fn.body:
        if not (isinstance(stmt, ast.Assign) and isinstance(stmt.targets[0], ast.Attribute)):
            continue

        notes = []
        i = stmt.lineno - 2  # whole-line comments directly above the assignment
        while i >= 0 and lines[i].strip().startswith("#"):
            text = lines[i].strip().lstrip("#").strip()
            if text.startswith("---") and text.endswith("---"):
                section = text.strip("- ")
            else:
                notes.insert(0, text)
            i -= 1

        # Anywhere in the statement's span, not only its last line -- see _trailing_comments.
        notes.extend(
            text
            for line, text in sorted(trailing.items())
            if stmt.lineno <= line <= stmt.end_lineno
        )

        yield section, stmt.targets[0].attr, ast.unparse(stmt.value), " ".join(notes)


def _cell(text):
    """Escape a value for a markdown table cell.

    An unescaped pipe silently truncates the row, and the field most likely to contain
    one is `amp_dtype`, whose entire documentation is the comment `auto | bf16 | fp16 |
    fp32`. Without this it renders as just "auto", and no build warning says so.
    """
    return text.replace("|", "\\|")


def _render_default(src):
    return "_unset_" if "placeholder(" in src else f"`{_cell(src)}`"


def _template_config():
    """`init`'s own config, as the site's worked example. -> str

    Read from the scaffold rather than retyped, for the reason where_things_go_page reads
    it: a second copy of a config is a copy that stops training and says nothing. The
    wheel job builds a project from this template and trains it every commit.
    """
    source = files("gatle_ignite").joinpath("_template", "configs", "{{project_name}}_v0.py-tpl")
    body = source.read_text(encoding="utf-8").replace("{{project_name}}", "my_project")
    tree = ast.parse(body)
    doc = ast.get_docstring(tree, clean=False)
    if doc is not None:
        # The module docstring says what this page's own prose just said. Dropped by line
        # number rather than by string, so a reworded scaffold still renders.
        body = "\n".join(body.split("\n")[tree.body[0].end_lineno :])
    return body.strip()


def config_page():
    cfg = base.base_config()
    out = io.StringIO()
    print("# Config fields\n", file=out)
    print(BANNER, file=out)
    print(
        "\nStart from `base_config()`: every optional field already has a value, so a config"
        " only states what it changes.\n",
        file=out,
    )

    print("\n## A config, whole\n", file=out)
    print(
        "What `gatle-ignite init` writes, minus its file docstring. It trains as it stands,"
        ' so it is also the shortest correct answer to "what must a config say?". The tables'
        " below are the menu of what else it *could* say.\n",
        file=out,
    )
    print('```python title="configs/my_project_v0.py"', file=out)
    print(_template_config(), file=out)
    print("```\n", file=out)

    current = None
    for section, name, default_src, note in _walk_base_config():
        if section != current:
            current = section
            print(f"\n## {section}\n", file=out)
            print("| Field | Type | Default | Notes |", file=out)
            print("|---|---|---|---|", file=out)
        try:
            type_name = cfg.get_type(name).__name__
        except Exception:
            type_name = type(cfg.get(name)).__name__
        required = " **(required)**" if name in base.REQUIRED_FIELDS else ""
        print(
            f"| `{name}`{required} | `{type_name}` | {_render_default(default_src)} | {_cell(note)} |",
            file=out,
        )

    print("\n## Fields not pre-set by `base_config()`\n", file=out)
    print(
        "These are known to the framework but deliberately absent from `base_config()`,"
        " because their *presence* is what carries the meaning. A ConfigDict accepts new"
        " keys, so a config sets them directly.\n",
        file=out,
    )
    print("| Field | Meaning |", file=out)
    print("|---|---|", file=out)
    for name, note in base.OPTIONAL_KNOWN.items():
        print(f"| `{name}` | {_cell(note)} |", file=out)

    print(
        "\n## Your own fields\n\n"
        "Any other field is left alone, so a config can carry values that only your own"
        " trainer or dataset reads.\n",
        file=out,
    )
    return out.getvalue()


