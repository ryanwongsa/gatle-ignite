def cli_page():
    out = io.StringIO()
    print("# The CLI\n", file=out)
    print(BANNER, file=out)
    print(
        "\n`python -m gatle_ignite <cmd>` is equivalent to `gatle-ignite <cmd>`. Use that"
        " form under SLURM.\n",
        file=out,
    )
    parser = build_parser()
    print("```text", file=out)
    print(parser.format_help().rstrip(), file=out)
    print("```", file=out)

    subparsers = parser._subparsers._group_actions[0].choices
    for name, sub in subparsers.items():
        print(f"\n## `gatle-ignite {name}`\n", file=out)
        print("```text", file=out)
        print(sub.format_help().rstrip(), file=out)
        print("```", file=out)
    return out.getvalue()


