"""Generate the reference pages from the code, at build time.

Nothing here is hand-maintained. The config fields, their defaults, types, section
headings and notes are read out of `gatle_ignite.config`; the entrypoint contracts come
from `dispatch.CONTRACTS`; the builtins are discovered by asking each module whether it
satisfies its contract; the CLI page is argparse's own help.

The point is that a field added to `base_config()` appears on the site with no docs edit,
and a renamed one cannot leave a stale name behind, because there is no second copy.
"""

import ast
import importlib
import inspect
import io
import pkgutil
import tokenize
from importlib.resources import files

import mkdocs_gen_files

from gatle_ignite.callbacks import logging as gi_logging
from gatle_ignite.cli.main import build_parser
from gatle_ignite.config import base
from gatle_ignite.dispatch import CONTRACTS

BANNER = "<!-- Generated by docs/gen_reference.py. Do not edit: edit the code it reads. -->"


