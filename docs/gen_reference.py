# (package, the entrypoint a module must expose to count, modules to skip)
BUILTIN_PACKAGES = (
    ("gatle_ignite.optimizers", "get_optimizer", ()),
    ("gatle_ignite.schedulers", "get_scheduler", ()),
    ("gatle_ignite.callbacks.backends", "Backend", ()),
)


def _params_of(entrypoint):
    """The configurable params of a builtin, read from its signature.

    Skips the positional plumbing the framework passes in (model, cfg, engine_type, ...)
    and reports what a config actually sets, with defaults.
    """
    import inspect

    framework_supplied = {
        "self",
        "model",
        "cfg",
        "train_dl",
        "optimizer",
        "trainer",
        "evaluator",
        "engine_type",
        "info",
        "dataset",
    }
    try:
        sig = inspect.signature(entrypoint)
    except (TypeError, ValueError):
        return ""

    parts = []
    for name, p in sig.parameters.items():
        if name in framework_supplied or p.kind is p.VAR_POSITIONAL:
            continue
        if p.kind is p.VAR_KEYWORD:
            parts.append("**kwargs")
            continue
        parts.append(name if p.default is p.empty else f"{name}={p.default!r}")
    return ", ".join(f"`{p}`" for p in parts)


def builtins_page():
    out = io.StringIO()
    print("# Builtins\n", file=out)
    print(BANNER, file=out)
    print(
        "\nBuiltins are ordinary modules with no special status. They are named by their"
        ' **full dotted path**. There is no alias table, so `"adamw"` does not resolve'
        ' and `"gatle_ignite.optimizers.adamw"` does. Swapping a builtin for your own is'
        " changing this string.\n",
        file=out,
    )
    print(
        '!!! note "One exception"\n'
        "    `cfg.logger_name` *does* accept short names: see the table at the bottom of"
        " this page, and [Logging](../steps/logging.md).\n",
        file=out,
    )

    for pkg_name, attr, exclude in BUILTIN_PACKAGES:
        pkg = importlib.import_module(pkg_name)
        print(f"\n## `{pkg_name}`\n", file=out)
        print(f"Each module exposes `{attr}`.\n", file=out)
        print("| Dotted path | What it is | Params |", file=out)
        print("|---|---|---|", file=out)
        for info in pkgutil.walk_packages(pkg.__path__, pkg_name + "."):
            leaf = info.name.rsplit(".", 1)[-1]
            if leaf.startswith("_") or leaf in exclude:
                continue
            mod = importlib.import_module(info.name)
            if not hasattr(mod, attr):
                continue
            blurb = (mod.__doc__ or "").strip().split("\n")[0]
            params = _params_of(getattr(mod, attr))
            print(f"| `{info.name}` | {_cell(blurb)} | {_cell(params)} |", file=out)

    print("\n## `cfg.logger_name`\n", file=out)
    print(
        "The one field that takes short names. It is a list of *enabled sinks*, not a"
        " component path, which is why it reads differently from everything above.\n",
        file=out,
    )
    print("| Name | Resolves to |", file=out)
    print("|---|---|", file=out)
    for name in gi_logging.BUILTIN_BACKENDS:
        print(f'| `"{name}"` | `gatle_ignite.callbacks.backends.{name}` |', file=out)
    for name in gi_logging.NOT_A_BACKEND:
        print(f'| `"{name}"` | **not a backend**: a flag handled by the trainer |', file=out)
    print(
        "\nAny name containing a dot is treated as a dotted path to your own module"
        " exposing `Backend(cfg)`.\n",
        file=out,
    )
    return out.getvalue()


