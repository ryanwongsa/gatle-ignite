def contracts_page():
    out = io.StringIO()
    print("# Entrypoint contracts\n", file=out)
    print(BANNER, file=out)
    print(
        "\nEvery component is selected by a dotted module path in the config, imported at"
        " runtime. There is no registry and no decorator: to add a component, write a module"
        " that exposes the expected name and point a config field at it.\n",
        file=out,
    )
    print("| Config field | Must expose | Contract |", file=out)
    print("|---|---|---|", file=out)
    for field, attr, contract, _fields in CONTRACTS:
        print(f"| `{_cell(field)}` | `{attr}` | {_cell(contract)} |", file=out)
    print(
        '\n!!! note "One exception"\n'
        "    `cfg.logger_name` is a list of enabled sinks and *does* accept short names"
        " for the builtins. See [Logging](../steps/logging.md).\n",
        file=out,
    )
    print(
        "\nA path that does not import, or a module missing its entrypoint, raises"
        " `ConfigError` naming the config field at fault and listing what the module"
        " actually exports.\n",
        file=out,
    )
    return out.getvalue()


