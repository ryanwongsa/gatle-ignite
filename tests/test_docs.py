def test_every_field_commented_in_the_source_renders_its_note():
    """The oracle is the source, read independently of the generator.

    A generator that loses a note reports the field as uncommented, so looping over its output
    would skip the very field that broke. `ruff format` moving a trailing note is one cause.
    """
    import ast
    import inspect
    import io
    import tokenize

    from gatle_ignite.config import base

    source = inspect.getsource(base)
    commented_lines = {
        tok.start[0]
        for tok in tokenize.generate_tokens(io.StringIO(source).readline)
        if tok.type == tokenize.COMMENT and tok.line[: tok.start[1]].strip()
    }
    fn = next(
        n
        for n in ast.parse(source).body
        if isinstance(n, ast.FunctionDef) and n.name == "base_config"
    )
    commented_fields = {
        stmt.targets[0].attr
        for stmt in fn.body
        if isinstance(stmt, ast.Assign)
        and isinstance(stmt.targets[0], ast.Attribute)
        and any(stmt.lineno <= line <= stmt.end_lineno for line in commented_lines)
    }

    # `| `name` **(required)** | `str` | _unset_ | the note |` -> ("name", "the note").
    # Split on unescaped pipes only: amp_dtype's note is itself a row of escaped ones.
    row_re = re.compile(r"^\|\s*`(\w+)`(?:\s*\*\*\(required\)\*\*)?\s*\|(.*)\|\s*$")
    notes = {}
    for line in _render_generated_pages()["reference/config.md"].splitlines():
        match = row_re.match(line)
        if match:
            notes[match.group(1)] = re.split(r"(?<!\\)\|", match.group(2))[-1].strip()

    assert len(commented_fields) > 20, (
        f"only {len(commented_fields)} commented fields found in the source -- this test's "
        "own parsing of config/base.py has broken, not the generator"
    )
    blank = sorted(f for f in commented_fields if not notes.get(f))
    assert not blank, (
        f"these fields carry a comment in config/base.py but render an empty Notes cell: "
        f"{blank}. The generator lost the comment between the source and the page."
    )


