# A signature a doc writes out longhand: `get_scheduler(cfg, train_dl, optimizer, engines)`.
_SIGNATURE_RE = re.compile(r"\b(get_[a-z_]+)\(([^)]*)\)")


def _normative_lines(text):
    """Code blocks and table rows: prose may quote a wrong signature so you recognise it."""
    fenced = False
    for line in text.splitlines():
        if line.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if fenced or line.startswith("|"):
            yield line


# Entrypoints a builtin implements. Trainer, Model, Loss and Transformation take task params.
_REFERENCE_IMPL = {
    "get_scheduler": "gatle_ignite.schedulers.cosine",
    "get_optimizer": "gatle_ignite.optimizers.adamw",
    "get_metric": "examples.synthetic.metrics.accuracy",
}


@pytest.mark.parametrize("path", DOC_FILES, ids=_doc_id)
def test_no_doc_advertises_an_entrypoint_signature_the_code_would_reject(path):
    """Only leading positional names, up to the first `**kwargs` or default, are compared.

    `get_optimizer(model, **params)` names what the framework passes, not all adamw takes. A
    non-identifier argument means a call, not a signature, so there is nothing to check.
    """
    import inspect

    bad = []
    for entrypoint, written in _SIGNATURE_RE.findall("\n".join(_normative_lines(path.read_text()))):
        module = _REFERENCE_IMPL.get(entrypoint)
        if module is None:
            continue
        documented = []
        for param in (p.strip() for p in written.split(",")):
            if param.startswith("*") or "=" in param:
                break  # the doc stops naming positionals here; so do we
            documented.append(param)
        if not documented or not all(p.isidentifier() for p in documented):
            continue
        real = list(
            inspect.signature(getattr(importlib.import_module(module), entrypoint)).parameters
        )
        if documented != real[: len(documented)]:
            bad.append(
                f"{entrypoint}({', '.join(documented)}) -- real: {entrypoint}({', '.join(real)})"
            )
    assert not bad, f"{_doc_id(path)} advertises signatures the code does not have: {bad}"


# A "where things go" table's last column. `gatle_ignite.optimizers.*` names a namespace.
_BUILTIN_IN_TABLE_RE = re.compile(r"gatle_ignite(?:\.[a-z_][a-z0-9_]*)+(\.\*)?")

_LAYOUT_TABLES = [ROOT / "src" / "gatle_ignite" / "_template" / "README.md-tpl"]


def _table_rows(text):
    for line in text.splitlines():
        if line.startswith("|") and line.count("|") == 5 and "---" not in line:
            yield [cell.strip().strip("`") for cell in line.strip().strip("|").split("|")]


@pytest.mark.parametrize("path", _LAYOUT_TABLES, ids=_doc_id)
def test_every_builtin_a_layout_table_offers_is_actually_selectable(path):
    """Importing is not enough: `gatle_ignite.data.helpers` imports but has no `get_sampler`."""
    from gatle_ignite.dispatch import CONTRACTS

    entrypoints = {attr for _field, attr, _contract, _fields in CONTRACTS}
    bad = []
    for row in _table_rows(path.read_text()):
        want, builtin = row[0], row[-1]
        for match in _BUILTIN_IN_TABLE_RE.finditer(builtin):
            dotted, is_namespace = match.group(0), match.group(1)
            if is_namespace:
                dotted = dotted[: -len(is_namespace)]
            module = importlib.import_module(dotted)
            if is_namespace:
                # A namespace is honest if any module under it is selectable.
                leaves = [
                    importlib.import_module(f"{dotted}.{p.stem}")
                    for p in Path(module.__file__).parent.glob("[a-z]*.py")
                    if not p.stem.startswith("_")
                ]
                if any(entrypoints & set(vars(leaf)) for leaf in leaves):
                    continue
            elif entrypoints & set(vars(module)):
                continue
            bad.append(f"{want!r} offers {match.group(0)}, which exposes no entrypoint")
    assert not bad, f"{_doc_id(path)} offers builtins a config cannot select: {bad}"


# --- the example pages' spines ------------------------------------------------------
#
# docs/hooks.py replaces each <!-- spine: example/config --> marker at build time.

EXAMPLE_PAGES = sorted((ROOT / "docs" / "examples").glob("*.md"))

# synthetic is the baseline every spine is measured against, so it has none of its own.
SPINE_EXEMPT = ("synthetic.md",)

_SPINE_MARKER = re.compile(r"^<!--\s*spine:\s*([\w.-]+)/([\w.-]+)\s*-->$", re.M)


def _hooks():
    spec = importlib.util.spec_from_file_location("gi_docs_hooks", ROOT / "docs" / "hooks.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _markers(path):
    return _SPINE_MARKER.findall(path.read_text())


@pytest.mark.parametrize("path", EXAMPLE_PAGES, ids=_doc_id)
def test_every_example_page_carries_a_resolvable_spine(path):
    """The spine is the only thing tying an example page back to the walk."""
    markers = _markers(path)
    if path.name in SPINE_EXEMPT:
        assert not markers, f"{_doc_id(path)} is the baseline; it must not carry a spine."
        return
    assert markers, (
        f"{_doc_id(path)} has no <!-- spine: example/config --> marker. Add one naming "
        "the config it documents."
    )
    # The hook's regex is anchored: a misplaced marker substitutes nothing, and the build passes.
    written = path.read_text().count("spine:")
    assert written == len(markers), (
        f"{_doc_id(path)} writes 'spine:' {written} times but only {len(markers)} are "
        "well-formed markers. A marker must start at column 0 with no trailing space."
    )
    hooks = _hooks()
    for example, stem in markers:
        block = hooks.spine(f"examples.{example}.configs.{stem}")
        assert block.strip(), f"{_doc_id(path)}: spine {example}/{stem} rendered empty."


def test_every_field_a_spine_names_is_documented_on_the_step_it_links_to():
    """A spine row must link to a step page that names its field."""
    hooks = _hooks()
    missing = []
    for path in EXAMPLE_PAGES:
        for example, stem in _markers(path):
            block = hooks.spine(f"examples.{example}.configs.{stem}")
            for row in block.splitlines():
                link = re.search(r"\]\(\.\./steps/([\w-]+)\.md\)", row)
                if not link:
                    continue
                page = (ROOT / "docs" / "steps" / f"{link.group(1)}.md").read_text()
                named = re.findall(r"`(\w+)`(?: =|:| is)", row)
                named += re.findall(r"overrides `(\w+)\(\)`", row)
                for field in named:
                    # `score_name` is inside `tester_score_name`.
                    if not re.search(rf"\b{re.escape(field)}\b", page):
                        missing.append(f"{example}/{stem}: `{field}` -> steps/{link.group(1)}.md")
    assert not missing, "spine rows naming a field their step page does not:\n  " + "\n  ".join(
        sorted(set(missing))
    )


@pytest.mark.parametrize("path", EXAMPLE_PAGES, ids=_doc_id)
def test_no_example_page_shows_code_for_a_step_it_does_not_change(path):
    """Re-showing an unchanged step makes a page read as a fresh start, not a continuation."""
    if path.name in SPINE_EXEMPT:
        return
    hooks = _hooks()
    changed = set()
    for example, stem in _markers(path):
        block = hooks.spine(f"examples.{example}.configs.{stem}")
        changed.update(re.findall(r"\]\(\.\./steps/([\w-]+)\.md\)", block))
    # Which step a --8<-- illustrates, from its directory. trainer/ is absent: every task
    # writes its own prep_batch.
    step_of_dir = {
        "dataloaders": "dataset",
        "models": "model",
        "losses": "loss",
        "metrics": "metrics",
        "optimizer": "optimizer",
        "augmentation": "dataset",
    }
    offenders = []
    for include in re.findall(r'--8<--\s+"(examples/[^"]+)"', path.read_text()):
        parts = Path(include).parts
        step = next((step_of_dir[p] for p in parts if p in step_of_dir), None)
        if step and step not in changed:
            offenders.append(f"{include} illustrates '{step}', which this example does not change")
    assert not offenders, f"{_doc_id(path)} shows code for an unchanged step:\n  " + "\n  ".join(
        offenders
    )


