def _exec_generator():
    """`(module, {path: markdown})`: the generator run with mkdocs_gen_files stubbed."""
    import importlib.util
    import io
    import sys

    written = {}

    class _Capture(io.StringIO):
        def __init__(self, path):
            super().__init__()
            self._path = path

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            written[self._path] = self.getvalue()
            return False

    stub = types.ModuleType("mkdocs_gen_files")
    stub.open = lambda path, mode="r": _Capture(path)
    stub.set_edit_path = lambda *a, **k: None

    real = sys.modules.get("mkdocs_gen_files")
    sys.modules["mkdocs_gen_files"] = stub
    try:
        spec = importlib.util.spec_from_file_location(
            "_gen_reference_under_test", ROOT / "docs" / "gen_reference.py"
        )
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        if real is None:
            del sys.modules["mkdocs_gen_files"]
        else:
            sys.modules["mkdocs_gen_files"] = real
    return module, written


def _render_generated_pages():
    """What docs/gen_reference.py would write, so tests read the page rather than its inputs."""
    return _exec_generator()[1]


