# Pages is world-readable. A bracketed character keeps a pattern from matching its own line.
FORBIDDEN = (
    r"ghp_[A-Za-z0-9]{20,}",  # GitHub PAT
    r"github[_]pat_[A-Za-z0-9_]{20,}",
    r"sk-[A-Za-z0-9]{20,}",  # OpenAI-style key
    r"xox[baprs]-[A-Za-z0-9-]{10,}",  # Slack token
    r"AKIA[0-9A-Z]{16}",  # AWS access key id
    r"-----BEGIN [A-Z ]*PRIVATE KEY",
    r"discord\.com/api/webhooks/[0-9]",  # a real webhook, not the env var name
    r"\b[0-9a-f]{40}\b",  # a bare 40-hex secret (W&B keys are this shape)
    r"/[w]orkspace/",  # internal absolute paths
    r"/home/[a-z0-9_-]+/",
)

# ConfigDict's own API, plus "py": `--config=cfg.py` is a filename, not a field access.
_IGNORED_ATTRS = {"get", "keys", "items", "values", "lock", "unlock", "to_json_best_effort", "py"}

# Not after a slash: a URL or a file path is not a module path.
_DOTTED_RE = re.compile(r"(?<![/\w])gatle_ignite(?:\.[a-z_][a-z0-9_]*)+(?:\.\{[a-z_,\s]+\})?")

# A brace shorthand that enumerates builtins compactly:
# `gatle_ignite.optimizers.{adam,adamw,sgd}` -> three real paths.
_BRACE_RE = re.compile(r"^(.*)\.\{([a-z_,\s]+)\}$")


def _expand(dotted):
    match = _BRACE_RE.match(dotted)
    if not match:
        return [dotted]
    stem, leaves = match.groups()
    return [f"{stem}.{leaf.strip()}" for leaf in leaves.split(",") if leaf.strip()]


def _doc_id(path):
    return str(path.relative_to(ROOT))


def _scan_text(text, patterns):
    hits = []
    for pattern in patterns:
        for match in re.finditer(pattern, text, re.IGNORECASE):
            line = text[: match.start()].count("\n") + 1
            hits.append(f"{pattern!r} at line {line}: {match.group(0)[:40]!r}")
    return hits


def _scan(path, patterns):
    return _scan_text(path.read_text(), patterns)


# Authored prose only: a fenced block or a --8<-- include is copied, not read.
MAX_PROSE_LINES = 60

# status.md is a ledger: capping it would mean deleting verified claims.
CAP_EXEMPT = ("status.md",)


def _prose_lines(text):
    """Authored prose lines: fenced blocks, their contents and snippet includes excluded."""
    count, inside = 0, False
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("```"):
            inside = not inside
            continue
        if inside or not stripped or stripped.startswith("--8<--"):
            continue
        count += 1
    return count


